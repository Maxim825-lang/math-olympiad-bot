def classify_problem(text: str) -> str:
    """
    Определить тему задачи по ключевым словам.

    Args:
        text: Текст задачи (title + условие).

    Returns:
        Название темы из списка TOPICS.
    """
    text_lower = text.lower()

    for topic, keywords in TOPIC_KEYWORDS:
        for kw in keywords:
            if kw in text_lower:
                return topic

    return "разное"


# ──────────────────────── Оценка сложности ───────────────────────────────────

def estimate_difficulty(text: str) -> float:
    """
    Примерно оценить сложность задачи от 1 до 5.

    Эвристики:
    - Длина текста
    - Наличие сложных слов/оборотов
    - Количество числовых данных
    """
    text_lower = text.lower()
    score = 2.0  # базовая сложность

    # Длина текста
    length = len(text)
    if length > 800:
        score += 1.0
    elif length > 400:
        score += 0.5
    elif length < 100:
        score -= 0.5

    # Сложные математические термины
    hard_terms = [
        "докажите", "доказать", "докажи",
        "наибольшее", "наименьшее", "оценку",
        "асимптотик", "бесконечн", "предел",
        "существует ли", "при всех", "для всех",
        "необходимо и достаточно",
    ]
    for term in hard_terms:
        if term in text_lower:
            score += 0.3

    # Простые конструкции — снижают сложность
    easy_terms = ["найдите", "вычислите", "сколько", "чему равно"]
    for term in easy_terms:
        if term in text_lower:
            score -= 0.2

    # Количество чисел в тексте (много чисел = сложнее)
    numbers = re.findall(r"\d+", text)
    if len(numbers) > 10:
        score += 0.5
    elif len(numbers) > 5:
        score += 0.2

    # Ограничить диапазоном [1, 5]
    return round(max(1.0, min(5.0, score)), 1)
